"""Project-local, offline installer. Python >=3.11, standard library only.

Preview is the default; --check never writes. No runtime calls or global config.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import sys
import tempfile
if sys.version_info < (3, 11):
    raise SystemExit("Richiesto Python 3.11+; installarlo separatamente, nessuna installazione automatica.")
import tomllib
from urllib.parse import unquote

VERSION = "1.0.0"
MANIFEST = "agent-kit/INSTALLATION.json"
START = "<!-- agent-pack:start -->"
END = "<!-- agent-pack:end -->"
ROOTS = {"codex": ".codex", "claude": ".claude", "cursor": ".cursor"}
SKILL_ROOTS = (".agents/skills", ".claude/skills")
LINK = re.compile(r"\[([^\]\n]+)\]\(([^)\n]+)\)")
NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")


class InvalidPack(ValueError):
    pass


class InstallPlan(dict):
    """Generated bytes plus the target state seen during conflict validation."""
    def __init__(self, outputs, observed):
        super().__init__(outputs)
        self.observed = observed


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def encoded(value) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode()


def read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        raise InvalidPack(f"JSON mancante o non valido: {path}: {exc}") from exc


def safe_path(root: Path, relative: str) -> Path:
    parts = PurePosixPath(relative)
    if not relative or parts.is_absolute() or ".." in parts.parts or "\\" in relative or ":" in relative:
        raise InvalidPack(f"Percorso non relativo al progetto: {relative}")
    path = root.joinpath(*parts.parts)
    # root is resolved by the entry point. Reject traversal lexically, then
    # inspect every component for redirection (also works for absent targets).
    if not root.is_absolute() or not path.is_relative_to(root):
        raise InvalidPack(f"Percorso fuori radice: {relative}")
    current = path
    while current != root:
        try:
            info = current.lstat()
        except FileNotFoundError:
            info = None
        if info and getattr(info, "st_reparse_tag", 0) in (0xA0000003, 0xA000000C):
            raise InvalidPack(f"Symlink/junction non supportato: {current}")
        if info and stat.S_ISLNK(info.st_mode):
            raise InvalidPack(f"Symlink non supportato: {current}")
        if info and current != path and not stat.S_ISDIR(info.st_mode):
            raise InvalidPack(f"Il padre non è una cartella: {current}")
        current = current.parent
    return path


def file_bytes(root: Path, relative: str) -> bytes:
    path = safe_path(root, relative)
    if not path.is_file():
        raise InvalidPack(f"Risorsa mancante: {relative}")
    return path.read_bytes()


def frontmatter(text: str, label: str) -> dict:
    """Read only required scalar keys, not an arbitrary YAML implementation."""
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise InvalidPack(f"Frontmatter assente/non valido: {label}")
    head = text.split("\n---\n", 1)[0][4:]
    result = {}
    for line in head.splitlines():
        match = re.match(r"^(name|description|disable-model-invocation):\s*(.*?)\s*$", line)
        if not match:
            continue
        key, value = match.groups()
        if key in result or not value or value in ("|", ">", "|-", ">-"):
            raise InvalidPack(f"Campo scalare duplicato/non supportato: {label}: {key}")
        if value.startswith('"'):
            try:
                value = json.loads(value)
            except ValueError as exc:
                raise InvalidPack(f"Stringa non supportata: {label}: {key}") from exc
        elif value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("''", "'")
        result[key] = value
    if not NAME.fullmatch(result.get("name", "")) or not result.get("description"):
        raise InvalidPack(f"name/description mancanti o non validi: {label}")
    return result


def relative_link(parent: str, target: str) -> str:
    return os.path.relpath(target, str(PurePosixPath(parent).parent)).replace("\\", "/")


def local_link(value: str):
    value = value.strip().strip("<>")
    if re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", value) or value.startswith("#"):
        return None
    return unquote(value.split("#", 1)[0])


def markdown_links_exist(source: Path, root: Path):
    text = source.read_text(encoding="utf-8-sig")
    for _, value in LINK.findall(text):
        part = local_link(value)
        if part is None:
            continue
        resolved = (source.parent / part).resolve()
        if not resolved.is_relative_to(root) or not resolved.is_file():
            raise InvalidPack(f"Link/risorsa mancante: {source.relative_to(root)} -> {value}")


def role_path(runtime: str, name: str) -> str:
    return f"{ROOTS[runtime]}/agents/{name}.{'toml' if runtime == 'codex' else 'md'}"


def render_role(name: str, role: dict, body: str, runtime: str, all_roles: dict, selected: set[str]) -> bytes:
    destination = role_path(runtime, name)
    skills = SKILL_ROOTS[1] if runtime == "claude" else SKILL_ROOTS[0]
    if runtime != "codex":
        body = re.sub(r"<!-- codex-preference:start -->.*?<!-- codex-preference:end -->\s*", "", body, flags=re.S)
    by_file = {value["file"]: key for key, value in all_roles.items()}

    def rewrite(match):
        label, link = match.groups()
        path = local_link(link)
        if path is None:
            return match.group(0)
        anchor = "#" + link.split("#", 1)[1] if "#" in link else ""
        if path.startswith("../Skills/"):
            target = skills + "/" + path[len("../Skills/"):]
        elif path in by_file:
            other = by_file[path]
            if other not in selected:
                return f"{label} (`{other}`, ruolo non incluso in questa installazione; il coordinatore verifica la destinazione prima della consegna)"
            target = role_path(runtime, other)
            # TOML instructions aren't Markdown headings.
            if runtime == "codex":
                anchor = ""
        elif path == "../README.md":
            target, anchor = "agent-kit/WORKFLOW.md", ""
        else:
            raise InvalidPack(f"Riferimento agente non mappato: {name} -> {link}")
        return f"[{label}]({relative_link(destination, target)}{anchor})"

    body = LINK.sub(rewrite, body)
    prefix = (f"ID registrato: `{name}`. Ambiente: {runtime}. La chat principale coordina le consegne. "
              "Usa solo gli strumenti esposti dalla sessione e i loro parametri reali. "
              "Se un ruolo o una skill necessaria manca, diagnostica e sospendi il lavoro dipendente.\n"
              f"I percorsi dei link sono relativi a questo file ({destination}); risolvili prima di leggerli.\n\n")
    if runtime == "codex":
        prefix += "I permessi sono ereditati dalla sessione: questo ruolo non crea una sandbox separata.\n\n"
    body = prefix + body
    if runtime == "codex":
        data = "\n".join(f"{key} = {json.dumps(value, ensure_ascii=False)}" for key, value in
                         (("name", name), ("description", role["description"]), ("developer_instructions", body))) + "\n"
        tomllib.loads(data)
    else:
        data = f"---\nname: {name}\ndescription: {json.dumps(role['description'], ensure_ascii=False)}\nmodel: inherit\n"
        if runtime == "cursor":
            data += f"readonly: {str(role['readonly']).lower()}\n"
        elif role["readonly"]:
            data += "tools: Read, Glob, Grep, Skill\n"
        # Other Claude roles inherit session tools; no manual-only preload.
        data += "---\n\n" + body
        frontmatter(data, destination)
    return data.encode()


def load_sources(pack: Path, phase: str):
    descriptor = read_json(pack / "pack.json")
    if descriptor.get("schema") != 1 or not NAME.fullmatch(descriptor.get("id", "")):
        raise InvalidPack("pack.json: schema/id non valido")
    role_map = read_json(safe_path(pack, "Skills/agent-configuration/references/roles.json"))
    if role_map.get("schema") != 1:
        raise InvalidPack("Versione roles.json non supportata")
    roles = role_map["roles"]
    selected = descriptor.get("phases", {}).get(phase)
    skills = descriptor.get("skills")
    for label, values in (("roles", selected), ("skills", skills)):
        if not isinstance(values, list) or not values or any(not isinstance(v, str) or not NAME.fullmatch(v) for v in values):
            raise InvalidPack(f"{label} mancanti/non validi per fase {phase}")
        if len(values) != len(set(values)):
            raise InvalidPack(f"Nomi duplicati in {label}")
    for name in selected:
        if name not in roles:
            raise InvalidPack(f"Ruolo senza mappatura: {name}")
    files = {}
    for name in skills:
        base = safe_path(pack, f"Skills/{name}")
        meta = frontmatter(file_bytes(pack, f"Skills/{name}/SKILL.md").decode("utf-8-sig").replace("\r\n", "\n"), name)
        if meta["name"] != name:
            raise InvalidPack(f"Nome skill/cartella divergente: {name} -> {meta['name']}")
        if meta.get("disable-model-invocation") == "true":
            policy = file_bytes(pack, f"Skills/{name}/agents/openai.yaml").decode("utf-8-sig")
            if not re.search(r"allow_implicit_invocation:\s*false", policy):
                raise InvalidPack(f"Politica esplicita Codex mancante: {name}")
        for source in sorted(base.rglob("*")):
            if "__pycache__" in source.parts or source.suffix == ".pyc":
                continue
            rel = source.relative_to(pack).as_posix()
            safe_path(pack, rel)
            if source.is_file():
                if source.suffix == ".md":
                    markdown_links_exist(source, pack)
                files[rel] = source.read_bytes()
    bodies = {}
    for name in selected:
        rel = "Agents/" + roles[name]["file"]
        bodies[name] = file_bytes(pack, rel).decode("utf-8-sig").replace("\r\n", "\n")
        markdown_links_exist(pack / rel, pack)
    return descriptor, roles, files, bodies


