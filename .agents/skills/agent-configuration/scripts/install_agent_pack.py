def section() -> bytes:
    return (START + "\n## Agenti e skills del progetto\n\n"
            "Per task coperti dai ruoli installati, la chat principale coordina la delega pertinente. "
            "Leggi [workflow e nomi registrati](agent-kit/WORKFLOW.md), poi solo le skills necessarie. "
            "Per capacità mancanti diagnostica prima del lavoro dipendente. Mantieni istruzioni e permessi di questo progetto.\n"
            + END).encode()


def extract_section(data: bytes, label: str):
    start, end = START.encode(), END.encode()
    if data.count(start) != data.count(end) or data.count(start) > 1:
        raise InvalidPack(f"Marcatori duplicati/incompleti: {label}")
    if start not in data:
        return None
    a, b = data.index(start), data.index(end) + len(end)
    if b <= a:
        raise InvalidPack(f"Marcatori invertiti: {label}")
    return a, b, data[a:b]


def validate_outputs(outputs: dict[str, bytes]):
    for rel, data in outputs.items():
        if not rel.endswith((".md", ".toml")):
            continue
        text = data.decode("utf-8-sig")
        if rel.endswith(".toml"):
            text = tomllib.loads(text)["developer_instructions"]
        for _, link in LINK.findall(text):
            target = local_link(link)
            if target is None:
                continue
            normalized = os.path.normpath(str(PurePosixPath(rel).parent / target)).replace("\\", "/")
            if normalized not in outputs:
                raise InvalidPack(f"Dipendenza non inclusa: {rel} -> {link}")


def duplicates(project: Path, outputs: dict[str, bytes], installed_roles: dict):
    """Check project-local discovery locations, including compatibility directories."""
    for runtime, root in ROOTS.items():
        expected = {name: role_path(runtime, name) for name in installed_roles}
        folder = safe_path(project, root + "/agents")
        if not folder.exists():
            continue
        for path in folder.rglob("*"):
            if path.suffix not in (".md", ".toml") or not path.is_file():
                continue
            rel = path.relative_to(project).as_posix()
            safe_path(project, rel)
            if rel in outputs:
                continue
            text = path.read_text(encoding="utf-8-sig")
            if path.suffix == ".toml":
                name = tomllib.loads(text).get("name")
            else:
                name = frontmatter(text.replace("\r\n", "\n"), rel)["name"]
            if name in expected:
                raise InvalidPack(f"Nome agente duplicato: {name}: {rel} / {expected[name]}")
    canonical = {PurePosixPath(p).parts[2]: data for p, data in outputs.items()
                 if p.startswith(".agents/skills/") and p.endswith("/SKILL.md")}
    # Extra resources in a managed skill can change its behavior even when
    # SKILL.md itself is unmodified (for example added policy metadata).
    for skill_root in SKILL_ROOTS:
        for name in canonical:
            folder = safe_path(project, f"{skill_root}/{name}")
            if not folder.exists():
                continue
            for path in folder.rglob("*"):
                if "__pycache__" in path.parts or path.suffix == ".pyc":
                    continue
                rel = path.relative_to(project).as_posix()
                safe_path(project, rel)
                if path.is_file() and rel not in outputs:
                    raise InvalidPack(f"Risorsa aggiunta nella skill installata, preservata: {rel}")
    for root in (".agents", ".claude", ".cursor", ".codex"):
        folder = safe_path(project, root + "/skills")
        if not folder.exists():
            continue
        for path in folder.rglob("SKILL.md"):
            rel = path.relative_to(project).as_posix()
            safe_path(project, rel)
            meta = frontmatter(path.read_text(encoding="utf-8-sig").replace("\r\n", "\n"), rel)
            name = meta["name"]
            if name not in canonical or rel in outputs:
                continue
            # Even equal SKILL.md can hide divergent resources or policy.
            tree = {p.relative_to(path.parent).as_posix(): file_bytes(project, p.relative_to(project).as_posix())
                    for p in path.parent.rglob("*") if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"}
            prefix = f".agents/skills/{name}/"
            intended = {p[len(prefix):]: data for p, data in outputs.items() if p.startswith(prefix)}
            if tree != intended:
                raise InvalidPack(f"Skill duplicata/divergente: {name}: {rel}")
            print(f"AVVISO copia aggiuntiva identica: {rel}; verificare selettore runtime")


def prepare(pack: Path, project: Path, phase: str):
    if not pack.is_dir() or not project.is_dir():
        raise InvalidPack("Pack e progetto devono essere cartelle esistenti")
    if project == pack or project.is_relative_to(pack):
        raise InvalidPack("La destinazione non può coincidere con il pack o esserne una sottocartella")
    if (project / ".codex/skills/prompt-repository-maintenance/SKILL.md").exists():
        raise InvalidPack("Destinazione laboratorio locale: preservare i ruoli separati, scegliere il progetto destinatario")
    descriptor, roles, skill_files, bodies = load_sources(pack, phase)
    key = descriptor["id"] + ":" + phase
    observed = {}

    def observe(rel):
        path = safe_path(project, rel)
        data = path.read_bytes() if path.exists() else None
        if rel in observed and observed[rel] != data:
            raise InvalidPack(f"File cambiato durante anteprima: {rel}")
        observed[rel] = data
        return data

    manifest_path = safe_path(project, MANIFEST)
    previous_manifest = observe(MANIFEST)
    old = json.loads(previous_manifest.decode("utf-8-sig")) if previous_manifest is not None else {"schema": 1, "files": {}, "packs": {}, "roles": {}}
    if old.get("schema") != 1 or not all(isinstance(old.get(k), dict) for k in ("files", "packs", "roles")):
        raise InvalidPack("Manifest incompatibile")
    combined_roles = dict(old["roles"])
    combined_roles.update({name: {"canonical": roles[name]["file"], "paths": {r: role_path(r, name) for r in ROOTS}} for name in bodies})
    outputs, origins = {}, {}
    # Retain previously installed packs, without needing their original folders.
    for rel, record in old["files"].items():
        current = observe(rel)
        if current is None:
            raise InvalidPack(f"File installato mancante: {rel}")
        measured = current
        if record.get("kind") == "section":
            extracted = extract_section(current, rel)
            measured = extracted[2] if extracted else b""
        if digest(measured) != record["sha256"]:
            raise InvalidPack(f"Personalizzazione/conflitto preservato: {rel}; confrontare prima di rigenerare")
        outputs[rel], origins[rel] = current, record.get("sources", [])
    desired = {}
    source_records = {}
    for rel, data in skill_files.items():
        for skill_root in SKILL_ROOTS:
            target = skill_root + "/" + rel[len("Skills/"):]
            desired[target] = data
            source_records[target] = [{"pack": key, "path": rel, "sha256": digest(data)}]
    for name, body in bodies.items():
        rel = "Agents/" + roles[name]["file"]
        for runtime in ROOTS:
            target = role_path(runtime, name)
            # Links only to roles from this pack, so installing another pack doesn't change this role's bytes.
            desired[target] = render_role(name, roles[name], body, runtime, roles, set(bodies))
            source_records[target] = [{"pack": key, "path": origin, "sha256": digest(file_bytes(pack, origin))}
                                      for origin in (rel, "Skills/agent-configuration/references/roles.json",
                                                     "Skills/agent-configuration/scripts/install_agent_pack.py")]
    # Detect removal/migration; never leave an obsolete managed role silently active.
    for rel, record in old["files"].items():
        if key in record.get("owners", []) and rel not in desired and record.get("kind") != "shared":
            raise InvalidPack(f"File non più previsto: {rel}; migrazione/rimozione manuale necessaria")
    records = dict(old["files"])
    for rel, data in desired.items():
        previous = records.get(rel)
        target = safe_path(project, rel)
        if target.exists() and not target.is_file():
            raise InvalidPack(f"Destinazione non è un file: {rel}")
        current = observe(rel)
        other_owners = set(previous.get("owners", [])) - {key} if previous else set()
        if current is not None and current != data:
            if not previous or not previous.get("managed"):
                raise InvalidPack(f"File preesistente preservato: {rel}")
            if other_owners:
                raise InvalidPack(f"Versioni incompatibili fra pack: {rel}; allineare prima {sorted(other_owners)}")
        owners = sorted(other_owners | {key})
        sources = sorted([s for s in origins.get(rel, []) if s.get("pack") != key] + source_records[rel],
                         key=lambda source: (source["pack"], source["path"], source["sha256"]))
        records[rel] = {"sha256": digest(data), "owners": owners, "sources": sources,
                        "managed": previous["managed"] if previous else current is None, "kind": "file"}
        outputs[rel] = data
    shared = {"agent-kit/WORKFLOW.md": workflow(combined_roles)}
    for rel, data in shared.items():
        target = safe_path(project, rel)
        current = observe(rel)
        if current is not None and rel not in records and current != data:
            raise InvalidPack(f"File di coordinamento preesistente preservato: {rel}")
        if rel in records and not records[rel].get("managed") and current != data:
            raise InvalidPack(f"File di coordinamento non posseduto, preservato: {rel}")
        outputs[rel] = data
        managed = records[rel]["managed"] if rel in records else not target.exists()
        records[rel] = {"sha256": digest(data), "owners": [], "sources": [], "managed": managed, "kind": "shared"}
    for rel in ("AGENTS.md", "CLAUDE.md"):
        path = safe_path(project, rel)
        current = observe(rel) or b""
        found = extract_section(current, rel)
        block = section()
        if found:
            if rel not in records and found[2] != block:
                raise InvalidPack(f"Sezione preesistente non gestita: {rel}")
            outputs[rel] = current[:found[0]] + block + current[found[1]:]
        else:
            outputs[rel] = current + (b"\n\n" if current else b"") + block + b"\n"
        records[rel] = {"sha256": digest(block), "owners": [], "sources": [], "managed": True, "kind": "section"}
    # Existing project instructions may contain unrelated links: only validate managed sections.
    link_outputs = {p: (section() if p in ("AGENTS.md", "CLAUDE.md") else b) for p, b in outputs.items()}
    validate_outputs(link_outputs)
    duplicates(project, outputs, combined_roles)
    packs = dict(old["packs"])
    packs[key] = {"descriptor_sha256": digest(file_bytes(pack, "pack.json")), "roles": sorted(bodies), "skills": descriptor["skills"]}
    manifest = {"schema": 1, "generator_version": VERSION, "generator_sha256": digest(Path(__file__).read_bytes()), "packs": packs, "roles": combined_roles, "files": records,
                "runtime_status": {r: "NOT_VERIFIED" for r in ROOTS}}
    outputs[MANIFEST] = encoded(manifest)
    return InstallPlan(outputs, observed)


def apply_outputs(project: Path, outputs: dict[str, bytes]):
    """Stage all files, replace manifest last, roll back replaced files on failure."""
    if not isinstance(outputs, InstallPlan):
        raise InvalidPack("Applicazione richiede un piano preparato con snapshot dei target")
    for rel, original in outputs.observed.items():
        path = safe_path(project, rel)
        current = path.read_bytes() if path.exists() else None
        if current != original:
            raise InvalidPack(f"File cambiato dopo anteprima: {rel}; ripetere il preflight")
    changes = [(rel, data) for rel, data in outputs.items()
               if not safe_path(project, rel).exists() or safe_path(project, rel).read_bytes() != data]
    changes.sort(key=lambda pair: (pair[0] == MANIFEST, pair[0]))
    before, staged, replaced, created_dirs = {}, {}, [], []
    try:
        for rel, data in changes:
            path = safe_path(project, rel)
            before[rel] = outputs.observed[rel]
            missing = []
            parent = path.parent
            while not parent.exists():
                missing.append(parent)
                parent = parent.parent
            for parent in reversed(missing):
                parent.mkdir()
                created_dirs.append(parent)
            fd, temporary = tempfile.mkstemp(prefix=".agent-pack-", dir=path.parent)
            staged[rel] = Path(temporary)
            with os.fdopen(fd, "wb") as stream:
                stream.write(data)
        # Detect edits made during staging before replacing any target.
        for rel, _ in changes:
            path = safe_path(project, rel)
            current = path.read_bytes() if path.exists() else None
            if current != before[rel]:
                raise InvalidPack(f"File cambiato durante installazione: {rel}")
        for rel, _ in changes:
            os.replace(staged[rel], safe_path(project, rel))
            replaced.append(rel)
    except BaseException:
        for rel in reversed(replaced):
            path = safe_path(project, rel)
            if before[rel] is None:
                path.unlink()
            else:
                path.write_bytes(before[rel])
        raise
    finally:
        for path in staged.values():
            if path.exists():
                path.unlink()
        for path in reversed(created_dirs):
            try:
                path.rmdir()  # Only empty directories created by this invocation.
            except OSError:
                pass


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pack", type=Path, required=True)
    parser.add_argument("--project", type=Path, required=True)
    parser.add_argument("--phase", choices=("project", "optimizer"), default="project")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--apply", action="store_true")
    modes.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if sys.version_info < (3, 11):
        parser.error("Richiesto Python 3.11+; installarlo separatamente")
    try:
        project, pack = args.project.resolve(), args.pack.resolve()
        outputs = prepare(pack, project, args.phase)
        changed = []
        for rel, data in sorted(outputs.items()):
            path = safe_path(project, rel)
            status = "CREATE" if not path.exists() else "UNCHANGED" if path.read_bytes() == data else "UPDATE"
            if status != "UNCHANGED":
                changed.append(rel)
                print(f"{status}: {rel}")
        if args.check:
            if changed:
                print(f"CHECK FAIL: {len(changed)} file mancanti/da aggiornare; nessuna scrittura")
                return 1
            print("CHECK OK: file, formati, dipendenze, hash e copie equivalenti; runtime NON VERIFICATI")
        elif args.apply:
            apply_outputs(project, outputs)
            print(f"APPLY OK: {len(changed)} file scritti; runtime NON VERIFICATI")
        else:
            print(f"PREVIEW: {len(changed)} operazioni; nessuna scrittura. Usare --apply poi --check.")
        return 0
    except (InvalidPack, OSError, ValueError, KeyError, TypeError) as exc:
        print(f"ERRORE: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
